#!/usr/bin/env python3
"""Append stable glyph IDs; generate matching BL616/FPGA assets together."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--monitor', type=Path, required=True)
    p.add_argument('--csv', type=Path, action='append', default=[], help='titles.csv or ROM root folder (recursive)')
    p.add_argument('--capacity', type=int, choices=[256,512,1024,2048,4096], default=1024)
    a = p.parse_args()
    fontdir = a.monitor / 'src/iosys/ui16'
    manifest_path = ROOT / 'ui/ui16_font_manifest.json'
    bank = json.loads(gzip.decompress((Path(__file__).with_name('shinonome16.json.gz')).read_bytes()))
    if manifest_path.exists():
        entries = json.loads(manifest_path.read_text())['glyphs']
    else:
        mapping = re.findall(r'\{\s*(0x[0-9a-fA-F]+),\s*(\d+)\s*\}', (ROOT/'ui/ui16_font_map.h').read_text())
        words = [int(x,16) for x in (fontdir/'font16_full.hex').read_text().split()]
        entries = [{'cp':int(cp,16),'id':int(gid),'rows':words[int(gid)*16:(int(gid)+1)*16]} for cp,gid in mapping]
        entries.insert(0, {'cp':32,'id':0,'rows':[0]*16})
    seen = {e['cp'] for e in entries}
    required = set(range(32,127)) | {0x25a1} | set(map(ord,"X/Y 戻る"))
    required |= {int(cp) for cp in bank if 0x3000 <= int(cp) <= 0x30ff}
    # Validate strict tab-separated CSV before generating any output.
    from titles_common import read_titles,csv_paths
    for path in csv_paths(a.csv):
        for _, name, title in read_titles(path):
            required.update(map(ord,title if title.strip(' \u3000') else name))
    missing = [cp for cp in sorted(required-seen) if str(cp) not in bank]
    if missing:
        raise ValueError('No source bitmap: '+', '.join(f'U+{cp:04X} {chr(cp)}' for cp in missing))
    for cp in sorted(required-seen):
        entries.append({'cp':cp,'id':max(e['id'] for e in entries)+1,'rows':bank[str(cp)]})
    if max(e['id'] for e in entries) >= a.capacity:
        raise ValueError(f"Need {max(e['id'] for e in entries)+1} slots; capacity is {a.capacity}")
    data = {'format':4,'capacity':a.capacity,'glyph_bits':12,'glyphs':entries}
    data['sha256'] = hashlib.sha256(json.dumps(data,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    manifest = json.dumps(data,ensure_ascii=False,indent=1)+'\n'
    words = [0]*(a.capacity*16)
    for e in entries: words[e['id']*16:e['id']*16+16] = e['rows']
    mapping = '#pragma once\n#include <cstdint>\n// Generated by build_font.py; keep paired with the FPGA assets.\n'
    mapping += 'struct Ui16FontEntry { std::uint32_t codepoint; std::uint16_t glyph; };\n'
    mapping += 'inline constexpr Ui16FontEntry ui16_font_map[] = {\n'
    mapping += ''.join(f"    {{0x{e['cp']:04X}, {e['id']}}},\n" for e in entries)+'};\n'
    # Validate everything above before writing. Re-run with the same inputs is deterministic.
    for dest in [manifest_path,fontdir/'font_manifest.json']:
        dest.write_text(manifest,encoding='utf-8')
    (ROOT/'ui/ui16_font_map.h').write_text(mapping)
    (fontdir/'font16_full.hex').write_text(''.join(f'{w:04x}\n' for w in words))
    (fontdir/'font16_table.h').write_text(mapping)
    for path,cpp in [(ROOT/'ui/ui16_config.h',True),(fontdir/'ui_config.svh',False)]:
        s=path.read_text()
        s=s.replace('// Generated by tools/gen_ui_config.py from config/ui_config.json. DO NOT EDIT.',
                    '// Glyph capacity/ROM fields are regenerated by tools/ui16/build_font.py.')
        values={'GLYPH_COUNT':a.capacity,'GLYPH_ID_BITS':12,'FONT_ROM_SIZE':a.capacity*16,'FONT_ADDR_BITS':(a.capacity*16-1).bit_length(),'ROW_COMMAND':15}
        for name,value in values.items():
            pattern = rf'(inline constexpr int {name} = )\d+' if cpp else rf'(`define UI_{name} )\d+'
            s,n=re.subn(pattern,lambda m:m[1]+str(value),s)
            if n!=1: raise ValueError(f'Missing config field {name} in {path}')
        path.write_text(s)
    print(f"Generated {len(entries)} mapped characters / {a.capacity} slots, font {len(words)*2} bytes")
    print('Font SHA256:',data['sha256'])


if __name__=='__main__':
    try: main()
    except (ValueError,OSError,KeyError) as e: raise SystemExit(str(e))
